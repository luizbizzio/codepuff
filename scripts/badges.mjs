// Developer tool: the achievement badges as pictures, and the table of them in docs/FEATURES.md (between its two `achievements:` markers).
//   node scripts/badges.mjs
// It writes docs/images/achievements/<id>.svg (one per achievement, as it looks once reached).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import en from '../src/core/i18n/en.js'
import { rewardFor } from '../src/core/rewards.js'
import { MILESTONES } from '../src/core/milestones.js'
import { TIER_NAMES, achievementSvg } from '../src/core/render/badge.js'

const ROOT = join(import.meta.dirname, '..')
mkdirSync(join(ROOT, 'docs', 'images', 'achievements'), { recursive: true })

const rows = MILESTONES.map(m => {
  writeFileSync(join(ROOT, 'docs', 'images', 'achievements', m.id + '.svg'), achievementSvg({ kind: m.kind, tier: m.tier, size: 64, title: en[m.key].replace('{n}', m.n) }))
  const reward = rewardFor(m.id)
  return `| <img src="images/achievements/${m.id}.svg" alt="${TIER_NAMES[m.tier]} badge" width="48"> | ${en[m.key].replace('{n}', m.n)} | ${TIER_NAMES[m.tier]} | ${reward ? en[reward.key] + ' (' + reward.type + ')' : '-'} |`
})

const table = `| Badge | Achievement | Metal | Unlocks |
| --- | --- | --- | --- |
${rows.join('\n')}
`

const path = join(ROOT, 'docs', 'FEATURES.md')
let text = readFileSync(path, 'utf8')
const start = '<!-- achievements:start (generated by scripts/badges.mjs) -->'
const end = '<!-- achievements:end -->'
const a = text.indexOf(start)
const b = text.indexOf(end)
if (a < 0 || b < a) throw new Error('docs/FEATURES.md has no achievements:start / achievements:end markers')
text = text.slice(0, a + start.length) + '\n\n' + table + '\n' + text.slice(b)
writeFileSync(path, text)
console.log(`${MILESTONES.length} badges, FEATURES.md table updated`)
