"""Developer tool, step 3 of 3: writes src/core/art/sprites.js from the analyzed sprites.

    python scripts/sprites/build.py [dir] [out_file]

Faces are erased from the sprites here (the pixels under each eye and mouth are filled from their surroundings), because
the engine redraws eyes and mouths for every expression. Everything else is the reference artwork shrunk to pixel size.
"""
import json
import sys
from collections import deque

import numpy as np

ALPHABET = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'

# Face features, in sprite pixels. eyeScale/mouthScale size the engine's expressions to the sprite's own eyes and mouth.
FACES = {
    'classic': dict(set='oval', eyeL=(24.7, 24.7), eyeR=(36.5, 24.5), mouth=(32.8, 28.6), eyeScale=0.62, mouthScale=0.95, defaultMouth='grin',
                    erase=[(22, 21, 28, 28), (34, 21, 40, 28), (28, 26, 37, 31)]),
    'fox': dict(set='oval', eyeL=(24.5, 22.8), eyeR=(37.2, 22.6), mouth=(31.8, 27.2), eyeScale=0.55, mouthScale=1.0, defaultMouth='grin', defaultEyes='happy',
                erase=[(21, 20, 29, 25), (33, 20, 41, 25), (28, 25, 36, 30), (26, 23, 32, 27, (38, 26))]),
    'bot': dict(set='arch', eyeL=(18.2, 24.5), eyeR=(30.4, 24.5), mouth=(25.2, 28.2), eyeScale=1.15, mouthScale=1.05, defaultMouth='smile', ink='cyan',
                erase=[(14, 20, 23, 28), (26, 20, 34, 28), (21, 26, 30, 31, (25, 26))]),
    'slime': dict(set='oval', eyeL=(22.2, 19.6), eyeR=(34.6, 19.6), mouth=(30.4, 22.8), eyeScale=0.7, mouthScale=1.0, defaultMouth='cat',
                  erase=[(19, 15, 26, 24), (31, 15, 38, 24), (27, 21, 34, 26)]),
    'mage': dict(set='dot', eyeL=(15.2, 26.6), eyeR=(25.6, 26.8), mouth=(21.0, 31.6), eyeScale=0.62, mouthScale=0.8, defaultMouth='smile',
                 erase=[(13, 24, 18, 30), (24, 24, 29, 30), (19, 30, 24, 32, (21, 29))]),
    'aquatic': dict(set='round', eyeL=(11.6, 22.4), eyeR=(24.8, 22.6), mouth=(18.2, 25.6), eyeScale=0.5, mouthScale=0.8, defaultMouth='cat',
                    erase=[(8, 19, 15, 26), (21, 19, 28, 26), (16, 24, 21, 27)]),
}

ORDER = ['classic', 'fox', 'bot', 'slime', 'mage', 'aquatic']


def inpaint(quant, rects):
    """Fills each rectangle from its surroundings. A rectangle written (x0, y0, x1, y1, (x, y)) is filled with the color at
    (x, y) instead: for a flat area like a screen, where the nearest pixels outside the rectangle are the frame."""
    h, w = quant.shape
    hole = np.zeros((h, w), bool)
    plain = []
    fills = []
    for rect in rects:
        (fills if len(rect) == 5 else plain).append(rect)
    for x0, y0, x1, y1 in plain:
        hole[max(0, y0): min(h, y1 + 1), max(0, x0): min(w, x1 + 1)] = True
    hole &= quant >= 0
    out = quant.copy()
    for x0, y0, x1, y1, (rx, ry) in fills:
        area = out[max(0, y0): min(h, y1 + 1), max(0, x0): min(w, x1 + 1)]
        area[area >= 0] = quant[ry, rx]
    quant = out.copy()
    q = deque()
    dist = np.full((h, w), -1, int)
    for y in range(h):
        for x in range(w):
            if quant[y, x] >= 0 and not hole[y, x]:
                dist[y, x] = 0; q.append((y, x))
    while q:
        y, x = q.popleft()
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            ny, nx = y + dy, x + dx
            if 0 <= ny < h and 0 <= nx < w and hole[ny, nx] and dist[ny, nx] < 0:
                dist[ny, nx] = dist[y, x] + 1
                out[ny, nx] = out[y, x]
                q.append((ny, nx))
    return out


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else 'out/sprites'
    target = sys.argv[2] if len(sys.argv) > 2 else 'src/core/art/sprites.js'
    analysis = json.load(open(f'{folder}/analysis.json'))
    lines = ['// GENERATED by scripts/sprites/*.py from the character reference sheets. Do not edit by hand.',
             '// Each sprite is indexed pixel art: `rows` use `.` for empty and one character per palette slot; `slots` lists',
             '// [color, class] where class says whether the color follows the user\'s body color, accent color, or never changes.',
             '// The eyes and mouths were erased from the artwork; the engine draws them for every expression at `face`.',
             'export const SPRITES = {']
    for ident in ORDER:
        a = analysis[ident]
        quant = np.load(f'{folder}/{ident}-quant.npy')
        f = FACES[ident]
        quant = inpaint(quant, f['erase'])
        h, w = quant.shape
        # Drop slots that are no longer used after the faces were erased.
        used = sorted({int(v) for v in quant.flatten() if v >= 0})
        remap = {old: new for new, old in enumerate(used)}
        rows = [''.join('.' if quant[y, x] < 0 else ALPHABET[remap[int(quant[y, x])]] for x in range(w)) for y in range(h)]
        slots = [[a['colors'][o], a['classes'][o]] for o in used]
        face = {k: v for k, v in f.items() if k != 'erase'}
        body = a['body'] or (200, 200, 200)
        accent = a['accent'] or (120, 120, 120)
        hexc = lambda c: '#%02x%02x%02x' % tuple(c)
        lines.append(f"  {ident}: {{")
        lines.append(f"    w: {w}, h: {h},")
        lines.append(f"    base: {{ body: '{hexc(body)}', accent: '{hexc(accent)}' }},")
        lines.append(f"    face: {json.dumps(face)},")
        lines.append(f"    slots: {json.dumps(slots)},")
        lines.append('    rows: [')
        for r in rows: lines.append(f"      '{r}',")
        lines.append('    ],')
        lines.append('  },')
    lines.append('}')
    open(target, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote', target, sum(len(l) for l in lines) // 1024, 'KB')


main()
