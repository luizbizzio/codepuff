// Developer tool: writes docs/MOOD-REVIEW.md, the sheet native speakers can check. It lists every word the pet reads as an insult or as
// thanks, language by language, straight from src/core/mood.js, so the sheet is never out of date.
//   node scripts/mood-review.mjs
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CJK_LISTS, KOREAN_LISTS, LEXICON } from '../src/core/mood.js'

const ROOT = join(import.meta.dirname, '..')
const unique = list => [...new Set(list)]
const words = list => (list.length ? unique(list).map(word => '`' + word + '`').join(' · ') : '–')

const section = (name, rows) => `### ${name}\n\n| What it is | Words |\n| --- | --- |\n${rows.map(([label, list]) => `| ${label} | ${words(list)} |`).join('\n')}\n`

const latin = LEXICON.map(language => section(language.name, [
  ['Insults (cost hearts when aimed at the assistant)', language.strong],
  ['Harsh criticism of the work (a flinch, no hearts lost)', language.mild],
  ['Phrases that are always aimed at the listener', language.phrases],
  ['Thanks and praise (words)', language.kind],
  ['Thanks and praise (phrases)', language.kindPhrases],
  ['Words that mean "you" (an insult near one is aimed at the assistant)', language.you],
  ['Words that mean "I" (an insult near one is the speaker\'s own)', language.self],
  ['Words that turn a sentence around ("not")', language.negation],
]))

const korean = section('Korean (a word is known by how it begins)', [
  ['Insults', KOREAN_LISTS.strong], ['Harsh criticism of the work', KOREAN_LISTS.mild], ['Always aimed at the listener', KOREAN_LISTS.phrases], ['Thanks and praise', KOREAN_LISTS.kind],
])
const cjk = section('Japanese and Chinese (no spaces: the words are looked for inside the text; `(?!り)` means "not followed by り")', [
  ['Insults', CJK_LISTS.strong], ['Harsh criticism of the work', CJK_LISTS.mild], ['Always aimed at the listener', CJK_LISTS.phrases],
  ['Words that mean "you"', CJK_LISTS.you], ['Words that mean "I"', CJK_LISTS.self], ['Thanks and praise', CJK_LISTS.kind],
])

const page = `# Reviewing the pet's word lists

The pet has one to five hearts for you. They drop when you are abusive to the assistant and rise with thanks (see [Hearts](FEATURES.md#hearts)).
To tell the difference, a message is read once, in memory, against the lists below; it is never stored, logged or sent anywhere.

The lists were written by the author, not by native speakers of every language, and they will have mistakes. **If you speak one of these
languages, please read its section and tell us what is wrong.** It takes a few minutes and it is the most useful thing you can do for
this part of the project.

## What to look for

1. **A word that should not be there.** It is normal in a programming conversation, or it only sometimes insults, so it would take
   hearts from someone who was not rude. (Example of what we avoided: the Italian *prima* means "first"; the English *show* is a command.)
2. **A word that is missing.** A common insult or a common way to say thanks that the pet does not know.
3. **A word in the wrong group.** Harsh criticism of the work ("this code is garbage") only makes the pet flinch; real abuse aimed at it costs hearts.
4. **A wrong form.** Languages that change their words (Russian, Polish, Turkish) are only covered for the commonest forms.

## How to send it

- Open an issue at <https://github.com/luizbizzio/codepuff/issues> with the language and the words to add or remove, or
- change the list yourself: it is a plain list in [\`src/core/mood.js\`](../src/core/mood.js), and add a sentence or two for it to
  \`test/mood.test.js\` (there is a table of examples for every language). \`npm test\` must still pass.

Accents and capital letters do not matter (the text is folded first), and an apostrophe joins a word ("don't" is read as "dont").

## The lists

${latin.join('\n')}
${korean}
${cjk}
<sub>Generated by <code>scripts/mood-review.mjs</code> from <code>src/core/mood.js</code>.</sub>
`

writeFileSync(join(ROOT, 'docs', 'MOOD-REVIEW.md'), page)
console.log('docs/MOOD-REVIEW.md', page.length, 'characters')
