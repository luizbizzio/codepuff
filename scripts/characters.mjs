// Developer tool: the animated pictures of every character in every state, and the pages that show them.
//   node scripts/characters.mjs
// It writes
//   docs/images/states/<character>/<state>.svg   one small animated SVG per character and state (the pictures the band draws)
//   docs/characters/<character>.md               one page per character: every animation and when it appears
// and rewrites the "What you see" block of the README (between its two `states:` markers): Foxy in 24 states, six to a row, and the
// list of characters that link to their pages.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { petSvg } from '../src/core/render/raster.js'
import { CHARACTER_BLURBS, CHARACTER_IDS, CHARACTER_NAMES } from '../src/core/art/defaults.js'

const ROOT = join(import.meta.dirname, '..')

// [state, name shown, when it appears]
const STATES = [
  ['idle', 'Idle', 'Nothing is happening: the agent is not working.'],
  ['thinking', 'Thinking', 'The agent is working on a response and no tool call is in flight.'],
  ['reading', 'Reading', 'The agent is reading files.'],
  ['searching', 'Searching', 'The agent is searching the project.'],
  ['investigating', 'Investigating', 'The agent reads or searches right after something failed: it is looking into the failure.'],
  ['coding', 'Coding', 'The agent is editing code.'],
  ['running', 'Running', 'A command is running.'],
  ['git', 'Git', 'A git command: a commit, a branch, a push.'],
  ['mcp', 'Connected tool', 'A tool from an MCP server is being used.'],
  ['testing', 'Testing', 'A recognized test run is in flight.'],
  ['web', 'Web', 'The agent is looking things up online.'],
  ['delegating', 'Subagents', 'Subagents are working: small helpers appear next to the pet.'],
  ['planning', 'Planning', 'The agent is updating its plan.'],
  ['success', 'Success', 'A test run was confirmed passed, or a commit was made.'],
  ['error', 'Error', 'Something really failed: a tool, the tests or the model request.'],
  ['permission', 'Needs you', 'The agent needs you: an approval or a question.'],
  ['waiting', 'Waiting', 'The turn is done and the agent waits for your next prompt.'],
  ['finished', 'Finished', 'The turn has just ended.'],
  ['tired', 'Tired', "Your plan's limit is nearly used up."],
  ['sad', 'Sad', 'The pet\'s hearts are low (it did not like what it was told).'],
  ['disconnected', 'Disconnected', 'No agent is connected, or the session ended.'],
  ['petted', 'Petted', 'You pressed the pet.'],
  ['giggle', 'Giggle', 'You pressed the pet several times.'],
  ['delighted', 'Delighted', 'You pressed the pet a lot, or thanked it.'],
  ['hurt', 'Hurt', 'Someone was rude to it. Hearts recover with time and kind words.'],
]
const GRID = STATES.filter(([state]) => state !== 'hurt')
const COLUMNS = 6
const HEIGHT = 120

const write = (path, text) => { mkdirSync(join(path, '..'), { recursive: true }); writeFileSync(path, text) }
const svgPath = (character, state) => `docs/images/states/${character}/${state}.svg`

for (const character of CHARACTER_IDS) {
  for (const [state] of STATES) {
    write(join(ROOT, svgPath(character, state)), petSvg({ character, state, helpers: state === 'delegating' ? 2 : 0, height: HEIGHT, crop: 'band' }))
  }
}

// ---- one page per character ---------------------------------------------------------------------------------------
for (const character of CHARACTER_IDS) {
  const name = CHARACTER_NAMES[character]
  const rows = STATES.map(([state, label, when]) => `| <img src="../images/states/${character}/${state}.svg" alt="${label}" width="${HEIGHT}"> | **${label}** | ${when} |`)
  const extra = character === 'fox' ? '\nWhen something fails, Foxy also floats a 404 over its head.\n' : ''
  const page = `# ${name}

<p align="center"><img src="../images/states/${character}/idle.svg" alt="${name}" height="200"></p>

${CHARACTER_BLURBS[character]}
${extra}
[All characters](../../README.md#what-you-see) · [Features](../FEATURES.md)

## Every animation

All the pictures are animated. Each one shows when it appears, for ${name} and for every other character: the states follow what the agent really does, and the last four are reactions to you.

| Picture | Animation | When it appears |
| --- | --- | --- |
${rows.join('\n')}

<sub>Generated by <code>scripts/characters.mjs</code>: the same pictures the Claude Code band draws.</sub>
`
  write(join(ROOT, 'docs', 'characters', character + '.md'), page)
}

// ---- the README block ---------------------------------------------------------------------------------------------
const cell = ([state, label]) => `    <td align="center"><img src="${svgPath('fox', state)}" alt="${label}" width="${HEIGHT}"><br><sub>${label}</sub></td>`
const grid = []
for (let i = 0; i < GRID.length; i += COLUMNS) grid.push('  <tr>\n' + GRID.slice(i, i + COLUMNS).map(cell).join('\n') + '\n  </tr>')

const IN_ROW = 4
const people = CHARACTER_IDS.map(character => `    <td align="center"><a href="docs/characters/${character}.md"><img src="${svgPath(character, 'idle')}" alt="${CHARACTER_NAMES[character]}" width="${HEIGHT}"><br><sub><b>${CHARACTER_NAMES[character]}</b></sub></a></td>`)
const list = []
for (let i = 0; i < people.length; i += IN_ROW) list.push('  <tr>\n' + people.slice(i, i + IN_ROW).join('\n') + '\n  </tr>')

const block = `Foxy in every state, as the animated pictures the band draws:

<div align="center">

<table>
${grid.join('\n')}
</table>

</div>

All eight characters have all of these. Pick one to see each of its animations and when it appears:

<div align="center">

<table>
${list.join('\n')}
</table>

</div>
`

const readme = readFileSync(join(ROOT, 'README.md'), 'utf8')
const START = '<!-- states:start (generated by scripts/characters.mjs) -->'
const END = '<!-- states:end -->'
const a = readme.indexOf(START)
const b = readme.indexOf(END)
if (a < 0 || b < a) throw new Error('the README has no states:start / states:end markers')
writeFileSync(join(ROOT, 'README.md'), readme.slice(0, a + START.length) + '\n\n' + block + '\n' + readme.slice(b))
console.log(`${CHARACTER_IDS.length * STATES.length} SVGs, ${CHARACTER_IDS.length} pages, README block updated`)
